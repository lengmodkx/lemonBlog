/** 常见后缀归一化：杭州市 / 杭州 → 杭州 */
function normalizeCityName(city: string): string {
  return city.replace(/(市|地区|自治州|自治县|县|区|盟|特别行政区)$/, '').trim();
}

/** 根据城市名解析经纬度；找不到时返回 null。 */
export function resolveCityCoords(city: string): [number, number] | null {
  const key = normalizeCityName(city);
  return CITY_COORDS[city] ?? CITY_COORDS[key] ?? null;
}
